"use client";

import { useState, type FormEvent } from "react";
import { Sparkles, BookText, ShieldAlert } from "lucide-react";
import Link from "next/link";
import { api } from "@/components/forms";
import { renderMarkdown } from "@/components/Markdown";

type Answer = { mode: "ai" | "materials" | "safety"; answer: string; notice?: string; sources: { title: string; text: string }[] };

export function AskBox({ topicId, aiEnabled }: { topicId: number; aiEnabled: boolean }) {
  const [q, setQ] = useState("");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [res, setRes] = useState<Answer | null>(null);

  async function ask(e: FormEvent) {
    e.preventDefault();
    if (q.trim().length < 3) return setError("Type a question of at least a few words.");
    setBusy(true);
    setError(null);
    setRes(null);
    try {
      setRes(await api<Answer>("POST", "/api/learn/ask", { topicId, question: q }));
    } catch (err) {
      setError((err as Error).message);
    } finally {
      setBusy(false);
    }
  }

  return (
    <div>
      <form onSubmit={ask} className="space-y-2">
        <label htmlFor="ask" className="sr-only">Your question</label>
        <textarea
          id="ask"
          className="textarea"
          rows={3}
          maxLength={1000}
          placeholder="e.g. Why do school bags have wide straps?"
          value={q}
          onChange={(e) => setQ(e.target.value)}
        />
        <button className="btn btn-primary w-full" disabled={busy}>
          {busy ? "Thinking…" : aiEnabled ? "Ask" : "Search approved material"}
        </button>
        <p className="hint">
          {aiEnabled
            ? "Answers are generated by AI from your teacher's approved material. AI can make mistakes: check with your teacher."
            : "AI is not switched on for this deployment. You will see the matching parts of the approved material."}{" "}
          Never type personal details.
        </p>
        <Link href={`/app/study?topic=${topicId}`} className="inline-flex items-center gap-1.5 text-xs font-semibold text-brand">
          <Sparkles className="w-3.5 h-3.5" aria-hidden /> Open the AI study assistant: notes, flashcards and practice
        </Link>
      </form>
      {error && <p role="alert" className="mt-3 text-sm text-bad">{error}</p>}
      {res && (
        <div className="mt-4 space-y-3" aria-live="polite">
          {res.mode === "safety" && (
            <div className="rounded-lg border border-[#d03b3b]/30 bg-[#d03b3b]/5 p-3 text-sm flex gap-2">
              <ShieldAlert className="w-4 h-4 mt-0.5 text-bad shrink-0" aria-hidden />
              <p>{res.answer}</p>
            </div>
          )}
          {res.mode === "ai" && (
            <div className="ai-card p-3">
              <p className="text-xs font-semibold text-brand flex items-center gap-1 mb-1"><Sparkles className="w-3.5 h-3.5" aria-hidden /> AI explanation</p>
              <div className="prose-school text-sm" dangerouslySetInnerHTML={{ __html: renderMarkdown(res.answer) }} />
            </div>
          )}
          {res.notice && <p className="text-xs text-muted">{res.notice}</p>}
          {res.mode !== "safety" &&
            (res.sources.length ? (
              <div>
                <p className="text-xs font-semibold text-muted flex items-center gap-1 mb-1.5"><BookText className="w-3.5 h-3.5" aria-hidden /> From approved material</p>
                <ul className="space-y-2">
                  {res.sources.map((s, i) => (
                    <li key={i} className="text-sm rounded-lg bg-surface-2 p-2.5">
                      <span className="block text-xs font-semibold text-ink-2 mb-0.5">{s.title}</span>
                      {s.text}
                    </li>
                  ))}
                </ul>
              </div>
            ) : (
              <p className="text-sm text-muted">No matching approved material was found. Ask your teacher about this.</p>
            ))}
        </div>
      )}
    </div>
  );
}
